public class _2Variable {
    public static void main(String[] args) {
        //Create
        int age;
        age = 11;
        System.out.println(age);
        int totalMarks = 20;
        System.out.println(totalMarks);
        //case sensitive
        int weight = 80;
        int WEIGHT = 90;
        System.out.println(weight);
        System.out.println(WEIGHT);
        // starting letters
        int marks = 10;
        int Marks = 19;
        int _marks= 30;
        int $marks = 36;
        System.out.println(marks);
        System.out.println(Marks);
        System.out.println(_marks);
        System.out.println($marks);
        //subsequent letters
        int height5 = 10;
        int height_love = 23;
        int height_ = 24;
        int heigt$ =12;
        System.out.println(height5);
        System.out.println(height_love);
        System.out.println(height_);
        System.out.println(heigt$);
    }
}
